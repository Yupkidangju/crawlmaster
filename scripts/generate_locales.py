def build_all() -> None:
    langs = ["ko", "en", "ja", "zh_tw", "zh_cn"]
    dicts: list[dict[str, str]] = [{} for _ in langs]

    for key, vals in CATALOG.items():
        for i, v in enumerate(vals):
            dicts[i][key] = v

    for mid, vals in MONSTERS.items():
        key = f"MONSTER_{mid.upper()}_NAME"
        for i, v in enumerate(vals):
            dicts[i][key] = v

    for iid, (names, descs) in ITEMS.items():
        nk = f"ITEM_{iid.upper()}_NAME"
        dk = f"ITEM_{iid.upper()}_DESC"
        for i in range(5):
            dicts[i][nk] = names[i]
            dicts[i][dk] = descs[i]

    for sid, (names, descs) in SKILLS.items():
        nk = f"SKILL_{sid.upper()}_NAME"
        dk = f"SKILL_{sid.upper()}_DESC"
        for i in range(5):
            dicts[i][nk] = names[i]
            dicts[i][dk] = descs[i]

    # 플레이스홀더 일치 검증
    ref_keys = set(dicts[0].keys())
    for idx, d in enumerate(dicts):
        assert set(d.keys()) == ref_keys, f"Key mismatch in {langs[idx]}"
        for k, val in d.items():
            p0 = set(re.findall(r"\{([^}]+)\}", dicts[0][k]))
            pi = set(re.findall(r"\{([^}]+)\}", val))
            assert p0 == pi, f"Placeholder mismatch for {k} in {langs[idx]}: {p0} vs {pi}"

    out_dir = Path("assets/lang")
    out_dir.mkdir(parents=True, exist_ok=True)
    for idx, code in enumerate(langs):
        p = out_dir / f"{code}.json"
        p.write_text(json.dumps(dicts[idx], ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        print(f"Wrote {p} ({len(dicts[idx])} keys)")


if __name__ == "__main__":
    build_all()
